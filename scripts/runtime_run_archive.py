"""Create and verify portable, deterministic runtime-run evidence archives.

Version 1 provides safe packaging and offline file-integrity verification. It does
not independently authenticate trust anchors or authorize runtime handoffs.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import stat
import tempfile
from pathlib import Path, PurePosixPath
from typing import Any

ARCHIVE_FORMAT = "hoadf.runtime-run-archive"
ARCHIVE_VERSION = "1.0"
MANIFEST_NAME = "MANIFEST.json"
_REQUIRED_METADATA = {
    "run_id", "workflow_id", "stage_ids", "skill_ids",
    "personal_ai_library_revision", "ai_toolbox_revision",
    "created_at", "run_status", "verification_policy",
}


class RuntimeArchiveError(ValueError):
    """Raised when an archive cannot be safely created or verified."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _json_bytes(value: Any) -> bytes:
    try:
        return (json.dumps(
            value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
            allow_nan=False,
        ) + "\n").encode("utf-8")
    except (TypeError, ValueError) as exc:
        raise RuntimeArchiveError("invalid_json_data") from exc


def _safe_relative_path(value: str) -> PurePosixPath:
    if not isinstance(value, str) or not value or "\\" in value:
        raise RuntimeArchiveError("unsafe_archive_path")
    path = PurePosixPath(value)
    if path.is_absolute() or any(part in {"", ".", ".."} for part in path.parts):
        raise RuntimeArchiveError("unsafe_archive_path")
    if path.as_posix() != value or ":" in path.parts[0]:
        raise RuntimeArchiveError("non_normalized_archive_path")
    return path


def _regular_source(root: Path, relative: str) -> Path:
    rel = _safe_relative_path(relative)
    base = root.resolve(strict=True)
    current = base
    for part in rel.parts:
        current = current / part
        try:
            if current.is_symlink():
                raise RuntimeArchiveError("source_symlink_not_allowed")
        except OSError as exc:
            raise RuntimeArchiveError("source_path_unavailable") from exc
    try:
        resolved = current.resolve(strict=True)
        resolved.relative_to(base)
    except (OSError, ValueError) as exc:
        raise RuntimeArchiveError("source_file_missing_or_outside_root") from exc
    mode = resolved.stat(follow_symlinks=False).st_mode
    if not stat.S_ISREG(mode):
        raise RuntimeArchiveError("source_must_be_regular_file")
    return resolved


def _archive_files(root: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for current, dirs, names in os.walk(root, topdown=True, followlinks=False):
        current_path = Path(current)
        for directory in list(dirs):
            candidate = current_path / directory
            if candidate.is_symlink():
                raise RuntimeArchiveError("archive_symlink_not_allowed")
        dirs.sort()
        for name in sorted(names):
            candidate = current_path / name
            if candidate.is_symlink():
                raise RuntimeArchiveError("archive_symlink_not_allowed")
            mode = candidate.stat(follow_symlinks=False).st_mode
            if not stat.S_ISREG(mode):
                raise RuntimeArchiveError("archive_non_regular_file")
            relative = candidate.relative_to(root).as_posix()
            _safe_relative_path(relative)
            files[relative] = candidate
    return files


def create_runtime_archive(
    source_root: Path,
    destination: Path,
    metadata: dict[str, Any],
    files: dict[str, str],
) -> dict[str, Any]:
    """Create an archive directory from an explicit archive-path -> source-path map.

    The caller supplies archive.json and the run report/contract/stage/trust
    files explicitly. Secrets and private keys are never discovered or copied
    implicitly. MANIFEST.json is generated by this function.
    """
    if not isinstance(metadata, dict) or not _REQUIRED_METADATA.issubset(metadata):
        raise RuntimeArchiveError("archive_metadata_missing_required_fields")
    if {"archive_format", "archive_version"}.intersection(metadata):
        raise RuntimeArchiveError("archive_metadata_uses_reserved_fields")
    if metadata.get("run_status") not in {"completed", "blocked", "incomplete"}:
        raise RuntimeArchiveError("invalid_run_status")
    if (
        not isinstance(metadata.get("stage_ids"), list) or not metadata["stage_ids"]
        or any(not isinstance(item, str) or not item for item in metadata["stage_ids"])
    ):
        raise RuntimeArchiveError("archive_stage_ids_required")
    if len(set(metadata["stage_ids"])) != len(metadata["stage_ids"]):
        raise RuntimeArchiveError("duplicate_archive_stage_id")
    if (
        not isinstance(metadata.get("skill_ids"), list)
        or len(metadata["skill_ids"]) != len(metadata["stage_ids"])
        or any(not isinstance(item, str) or not item for item in metadata["skill_ids"])
    ):
        raise RuntimeArchiveError("archive_skill_ids_must_match_stages")
    if not isinstance(metadata.get("verification_policy"), dict):
        raise RuntimeArchiveError("archive_verification_policy_required")
    if not isinstance(files, dict) or not files:
        raise RuntimeArchiveError("archive_file_map_required")

    source_base = Path(source_root).resolve(strict=True)
    target = Path(destination).absolute()
    if target.exists() or target.is_symlink():
        raise RuntimeArchiveError("archive_destination_already_exists")
    if MANIFEST_NAME in files:
        raise RuntimeArchiveError("manifest_is_generated_not_supplied")
    normalized: dict[str, str] = {}
    for archive_name, source_name in files.items():
        relative = _safe_relative_path(archive_name).as_posix()
        if relative in normalized:
            raise RuntimeArchiveError("duplicate_archive_path")
        if relative in {"archive.json", MANIFEST_NAME}:
            raise RuntimeArchiveError("reserved_archive_path")
        normalized[relative] = source_name

    metadata_bytes = _json_bytes({
        "archive_format": ARCHIVE_FORMAT,
        "archive_version": ARCHIVE_VERSION,
        **metadata,
    })
    temp_parent = target.parent
    temp_parent.mkdir(parents=True, exist_ok=True)
    temp_dir = Path(tempfile.mkdtemp(prefix=".runtime-archive-", dir=temp_parent))
    try:
        (temp_dir / "archive.json").write_bytes(metadata_bytes)
        for archive_name in sorted(normalized):
            source = _regular_source(source_base, normalized[archive_name])
            output = temp_dir.joinpath(*_safe_relative_path(archive_name).parts)
            output.parent.mkdir(parents=True, exist_ok=True)
            data = source.read_bytes()
            output.write_bytes(data)
        manifest_entries = []
        for relative, path in sorted(_archive_files(temp_dir).items()):
            data = path.read_bytes()
            manifest_entries.append({
                "path": relative,
                "size": len(data),
                "sha256": _sha256(data),
                "media_type": (
                    "application/json" if relative.endswith(".json")
                    else "application/octet-stream"
                ),
            })
        manifest = {
            "manifest_version": "1.0",
            "canonicalization": "python-json-sort-keys-compact-utf8-v1",
            "entries": manifest_entries,
        }
        (temp_dir / MANIFEST_NAME).write_bytes(_json_bytes(manifest))
        os.replace(temp_dir, target)
    except Exception:
        shutil.rmtree(temp_dir, ignore_errors=True)
        raise
    return verify_runtime_archive(target)


def verify_runtime_archive(archive_root: Path) -> dict[str, Any]:
    """Verify exact archive file set, path safety, sizes and SHA-256 digests."""
    root = Path(archive_root)
    if root.is_symlink() or not root.is_dir():
        raise RuntimeArchiveError("archive_root_must_be_directory")
    root = root.resolve(strict=True)
    files = _archive_files(root)
    manifest_path = files.get(MANIFEST_NAME)
    if manifest_path is None:
        raise RuntimeArchiveError("archive_manifest_missing")
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RuntimeArchiveError("archive_manifest_invalid_json") from exc
    if not isinstance(manifest, dict) or manifest.get("manifest_version") != "1.0":
        raise RuntimeArchiveError("unsupported_archive_manifest")
    if manifest.get("canonicalization") != "python-json-sort-keys-compact-utf8-v1":
        raise RuntimeArchiveError("unsupported_archive_canonicalization")
    entries = manifest.get("entries")
    if not isinstance(entries, list):
        raise RuntimeArchiveError("archive_manifest_entries_required")

    declared: dict[str, dict[str, Any]] = {}
    ordered_paths: list[str] = []
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != {"path", "size", "sha256", "media_type"}:
            raise RuntimeArchiveError("invalid_archive_manifest_entry")
        relative = _safe_relative_path(entry["path"]).as_posix()
        if relative == MANIFEST_NAME or relative in declared:
            raise RuntimeArchiveError("duplicate_or_reserved_manifest_path")
        if not isinstance(entry["size"], int) or isinstance(entry["size"], bool) or entry["size"] < 0:
            raise RuntimeArchiveError("invalid_manifest_file_size")
        digest = entry["sha256"]
        if not isinstance(digest, str) or len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
            raise RuntimeArchiveError("invalid_manifest_sha256")
        if not isinstance(entry["media_type"], str) or not entry["media_type"]:
            raise RuntimeArchiveError("invalid_manifest_media_type")
        declared[relative] = entry
        ordered_paths.append(relative)
    if ordered_paths != sorted(ordered_paths):
        raise RuntimeArchiveError("archive_manifest_not_sorted")

    actual_paths = set(files) - {MANIFEST_NAME}
    if actual_paths != set(declared):
        raise RuntimeArchiveError("archive_file_set_mismatch")
    verified = []
    for relative in sorted(declared):
        data = files[relative].read_bytes()
        entry = declared[relative]
        if len(data) != entry["size"]:
            raise RuntimeArchiveError(f"archive_file_size_mismatch:{relative}")
        digest = _sha256(data)
        if digest != entry["sha256"]:
            raise RuntimeArchiveError(f"archive_file_digest_mismatch:{relative}")
        verified.append({"path": relative, "sha256": digest, "size": len(data)})

    metadata_path = files.get("archive.json")
    if metadata_path is None:
        raise RuntimeArchiveError("archive_metadata_missing")
    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RuntimeArchiveError("archive_metadata_invalid_json") from exc
    if (
        not isinstance(metadata, dict)
        or metadata.get("archive_format") != ARCHIVE_FORMAT
        or metadata.get("archive_version") != ARCHIVE_VERSION
        or not _REQUIRED_METADATA.issubset(metadata)
    ):
        raise RuntimeArchiveError("invalid_archive_metadata")
    return {
        "status": "archive_integrity_verified",
        "archive_format": ARCHIVE_FORMAT,
        "archive_version": ARCHIVE_VERSION,
        "manifest_sha256": _sha256(manifest_path.read_bytes()),
        "file_count": len(verified),
        "files": verified,
        "run_id": metadata["run_id"],
        "workflow_id": metadata["workflow_id"],
        "run_status": metadata["run_status"],
        "verification_scope": "file_integrity_only",
        "limitations": [
            "The manifest is not independently signed; its hash requires an external trust anchor.",
            "Version 1 verifies package file integrity only, not Ed25519 signatures, TSA responses, or registry history.",
            "Archive verification never authorizes a live runtime handoff or external action.",
        ],
    }
